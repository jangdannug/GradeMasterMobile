// Generates src/theme/tokens.generated.ts from the web frontend's global.css.
// Usage: node scripts/gen-mobile-themes.mjs [path/to/global.css]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cssPath = resolve(here, process.argv[2] ?? '../../GradeMasterFrontend/client/global.css');
const outPath = resolve(here, '../src/theme/tokens.generated.ts');

const THEME_SELECTORS = {
  mist: ':root',
  slate: '[data-theme="slate"]',
  paper: '[data-theme="paper"]',
  sage: '[data-theme="sage"]',
  dark: '.dark',
};

// Only the tokens mobile consumes: semantic tokens, the tint steps, and the sidebar set
const WANTED = [
  'background', 'foreground', 'card', 'card-foreground', 'popover', 'popover-foreground',
  'primary', 'primary-foreground', 'primary-hover', 'primary-50', 'primary-100',
  'secondary', 'secondary-foreground', 'muted', 'muted-foreground',
  'selected', 'selected-foreground', 'accent', 'accent-foreground',
  'border', 'input', 'ring', 'table-header',
  'academic', 'academic-foreground', 'academic-hover',
  'highlight', 'highlight-foreground',
  'success', 'success-foreground', 'success-50',
  'warning', 'warning-foreground', 'warning-50',
  'destructive', 'destructive-foreground', 'destructive-50',
  'info', 'info-foreground', 'info-50',
  'sidebar-background', 'sidebar-foreground', 'sidebar-primary', 'sidebar-primary-foreground',
  'sidebar-accent', 'sidebar-accent-foreground', 'sidebar-border', 'sidebar-muted',
  'sidebar-primary-text', 'sidebar-ring',
  'chart-1', 'chart-2',
];

const css = readFileSync(cssPath, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');

// Body of the first `selector { ... }` block that declares custom properties
function blockBody(selector) {
  let from = 0;
  for (;;) {
    const at = css.indexOf(selector, from);
    if (at < 0) throw new Error(`selector not found: ${selector}`);
    const open = css.indexOf('{', at);
    const between = css.slice(at + selector.length, open);
    from = at + selector.length;
    if (between.trim() !== '') continue; // selector appears inside another rule
    let depth = 0;
    for (let i = open; i < css.length; i++) {
      if (css[i] === '{') depth++;
      else if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
    }
    throw new Error(`unbalanced block: ${selector}`);
  }
}

function parseVars(body) {
  const vars = {};
  for (const m of body.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars[m[1]] = m[2].trim();
  return vars;
}

const hex2 = (n) => Math.round(n * 255).toString(16).padStart(2, '0').toUpperCase();
function hslToHex(h, s, l) {
  s /= 100;
  l /= 100;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => {
    const k = (n + h / 30) % 12;
    return l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
  };
  return `#${hex2(f(0))}${hex2(f(8))}${hex2(f(4))}`;
}

function toHex(value, name) {
  if (/^#[0-9a-f]{6}$/i.test(value)) return value.toUpperCase();
  const m = value.match(/^([\d.]+)\s+([\d.]+)%\s+([\d.]+)%$/);
  if (!m) throw new Error(`unsupported value for --${name}: ${value}`);
  return hslToHex(+m[1], +m[2], +m[3]);
}

const root = parseVars(blockBody(':root'));
const camel = (k) => k.replace(/-(\w)/g, (_, c) => c.toUpperCase());

const lines = [
  '// Generated by scripts/gen-mobile-themes.mjs from GradeMasterFrontend/client/global.css. Do not edit.',
  '',
  'export type WebTokens = Record<string, string>;',
  '',
  'export const WEB_TOKENS = {',
];
for (const [id, selector] of Object.entries(THEME_SELECTORS)) {
  // Light themes override only some tokens; the rest come from :root
  const vars = { ...root, ...parseVars(blockBody(selector)) };
  lines.push(`  ${id}: {`);
  for (const name of WANTED) {
    if (!(name in vars)) throw new Error(`--${name} missing for ${id}`);
    lines.push(`    ${camel(name)}: '${toHex(vars[name], name)}',`);
  }
  lines.push('  },');
}
lines.push('} as const satisfies Record<string, WebTokens>;', '');
writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${outPath}`);
